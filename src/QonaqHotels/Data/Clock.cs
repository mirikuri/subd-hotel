namespace QonaqHotels.Data;

// Единый источник «сегодня» для бизнес-дат: заезд/выезд, приём и увольнение.
// В БД это столбцы типа date (без часового пояса), поэтому считаем по локальному времени сервера
// приложения. Нельзя смешивать с DateTime.UtcNow: в Казахстане (UTC+5) с 00:00 до 05:00
// UTC-дата ещё вчерашняя, и проверки «не в прошлом» / «уже уволен» расходятся.
//
// Метки времени (вход, блокировка, создание брони) хранятся в timestamptz
// и ставятся в SQL через now() — так их задаёт один источник, сервер БД.
public static class Clock
{
    public static DateOnly Today => DateOnly.FromDateTime(DateTime.Now);
}
